-- AstroMaze schema for Supabase (Postgres)
-- Run this first in: Supabase dashboard -> SQL Editor

-- citext = case-insensitive text. MySQL compared usernames/emails
-- case-insensitively; this keeps login, uniqueness and search behaving the same.
create extension if not exists citext with schema extensions;

create table public.users (
  user_id         integer generated by default as identity primary key,
  username        extensions.citext not null unique check (char_length(username) <= 50),
  email           extensions.citext not null unique check (char_length(email) <= 100),
  password        varchar(255) not null,
  role            text not null default 'user' check (role in ('admin', 'user')),
  created_at      timestamptz not null default now(),
  is_active       smallint not null default 1,
  profile_picture varchar(255)
);

create table public.game_records (
  game_id        integer generated by default as identity primary key,
  user_id        integer not null
                   references public.users (user_id) on delete cascade on update cascade,
  score          integer not null default 0,
  orbs_collected integer not null default 0,
  fuel_remaining integer not null default 0,
  game_status    text not null check (game_status in ('won', 'lost')),
  played_at      timestamptz not null default now()
);

create index game_records_user_id_idx on public.game_records (user_id);

-- IMPORTANT: Supabase exposes public tables through its REST API using the
-- public "anon" key. Turning on RLS (with no policies) blocks that access.
-- AstroMaze connects directly as the postgres role, which bypasses RLS,
-- so the app keeps working.
alter table public.users        enable row level security;
alter table public.game_records enable row level security;
